<p>Если все этапы называют одной «заявкой», статусы быстро теряют смысл. Фраза «заявка согласована» может означать, что руководитель не возражает, поставщик уже подтвердил заказ или бухгалтерия поставила счет в оплату. Поэтому статус должен описывать завершенное действие: потребность проверена, источник выбран, заказ размещен, поставка подтверждена, принято на объекте.</p>

