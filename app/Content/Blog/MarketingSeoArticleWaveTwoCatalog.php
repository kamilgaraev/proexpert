<p>Заявка фиксирует, какой ресурс нужен строительному объекту, в каком объеме, к какой дате и для какой работы. Внутри компании она запускает проверку и снабжение. Запрос поставщику, коммерческое предложение, счет, заказ и накладная появляются позже и решают другие задачи.</p>

