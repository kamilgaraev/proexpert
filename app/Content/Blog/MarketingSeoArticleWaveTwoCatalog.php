<h2>Что такое общий журнал работ</h2>

<p>Общий журнал — документ, в котором учитывается выполнение работ в процессе строительства, реконструкции или капитального ремонта объекта капитального строительства. Он содержит сведения об участниках и инженерно-техническом персонале, специальных журналах, ходе работ, строительном контроле и государственном строительном надзоре.</p>

<p>Это не дневник прораба в свободной форме и не реестр актов. Запись должна позволять понять, какая работа выполнялась, где именно, в каком объеме и при каких условиях. Для проверяющего журнал связывает хронологию производства с контролем и комплектом документов.</p>

<p>Общий журнал также не следует автоматически отождествлять с любым документом, который в компании называют КС-6 или журналом производства работ. Название похоже, но применимая форма определяется нормативными требованиями и условиями конкретного строительства. Форма КС-6 существует как унифицированная форма первичного учета, а приказ № 1026/пр устанавливает актуальную форму и порядок общего журнала для предусмотренного им случая. До открытия журнала нужно определить основание, а не покупать привычный бланк по старому образцу.</p>

<h2>Нормативная база на 2026 год</h2>

