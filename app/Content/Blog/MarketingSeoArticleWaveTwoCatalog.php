<h2>Как собирать подтвержденный факт</h2>

<p>Факт должен возникать рядом с производством. Прораб фиксирует выполненный объем по участку и дате, прикладывает подтверждение и указывает препятствия. Проверяющий принимает запись полностью, частично либо возвращает с конкретной причиной. После принятия факт становится доступен для отчета и прогноза.</p>

<p>Фотография полезна как подтверждение, но не является измерением сама по себе. По общему виду стены нельзя надежно определить площадь и соответствие проекту. Запись должна содержать измеримую величину или однозначно завершенный участок, а фотография, схема или акт подтверждают контекст.</p>

<p>Нельзя смешивать дату выполнения и дату внесения. Если сотрудник в понедельник занес объем за прошлую пятницу, производственный факт относится к пятнице, а история системы должна показать поздний ввод. Это важно для анализа дисциплины данных и восстановления реальной последовательности событий.</p>

<h2>Как рассчитывать отклонение</h2>

<p>Для каждого показателя заранее задается единица и знак. По объему удобно считать «факт минус план»: отрицательное значение означает недовыполнение. По затратам часто используют «прогноз минус бюджет»: положительное значение означает ожидаемый перерасход. Подпись должна исключать двойное толкование.</p>

<p>Одновременно полезны абсолютное и относительное отклонения. Минус 100 м² может быть несущественным для фасада в 20 000 м² и критичным для захватки в 150 м². Процент без абсолютного значения тоже вводит в заблуждение, особенно на малом объеме.</p>

<p>Для незавершенной работы оценивают остаток и производительность. Простой прогноз окончания получается делением остаточного объема на устойчивую выработку с учетом доступных смен. Но среднее нельзя использовать механически: фронт может закончиться, состав бригады измениться, а часть операций иметь технологическое ожидание.</p>

<h2>План, факт и прогноз нельзя смешивать</h2>

<ul>
<li><strong>План</strong> отвечает, что было утверждено до начала отчетного периода.</li>
<li><strong>Факт</strong> отвечает, что подтверждено на конкретную дату.</li>
<li><strong>Прогноз</strong> отвечает, какой результат ожидается с учетом текущего состояния.</li>
</ul>

<p>Если руководитель решил изменить последовательность, новый прогноз становится рабочим ориентиром, но исходный план остается для анализа. Новая базовая версия появляется только после формального пересмотра. Тогда можно видеть и первоначальное отклонение, и эффект принятого решения.</p>

<p>В статье <a href="/blog/grafik-proizvodstva-rabot-v-stroitelstve">о графике производства работ</a> подробно разобраны зависимости и критический путь. В план-факте важно перенести эту логику на отчетную дату: просрочка некритичной операции и задержка работы без временного резерва требуют разной реакции.</p>

<h2>Как контролировать бюджет до оплаты</h2>

<p>Отчет по банковской выписке показывает уже совершившееся. Для раннего контроля нужны обязательства. Подписанный договор, подтвержденный заказ, принятая заявка на дополнительную работу и согласованная поставка создают будущую нагрузку на бюджет еще до счета.</p>

<p>По каждой статье полезно видеть:</p>

<ul>
<li>утвержденный лимит и все версии изменений;</li>
<li>сумму договоров и заказов;</li>
<li>подтвержденный объем выполнения или поставки;</li>
<li>начислено и предъявлено к оплате;</li>
<li>фактически оплачено;</li>
<li>оценку стоимости оставшегося объема;</li>
<li>прогноз итоговой стоимости.</li>
</ul>

<p>Если договор заключен на 8 млн рублей, выполнено на 3 млн, а оплачено 2 млн, нельзя считать фактом только платеж. Для кассы факт равен 2 млн, для производства — подтвержденному объему, для обязательств — условиям договора. Панель должна показывать эти слои отдельно.</p>

<h2>Еженедельный цикл план-факта</h2>

<ol>
<li>Зафиксировать отчетную дату и закрыть прием факта за период.</li>
<li>Проверить критичные и крупные отклонения по источникам.</li>
<li>Обновить остаточные объемы, производительность и ограничения.</li>
<li>Пересчитать прогноз сроков и итоговой стоимости.</li>
<li>Определить не больше нескольких решений с владельцами и сроками.</li>
<li>На следующем цикле проверить исполнение решений, а не только новые цифры.</li>
</ol>

<p>Совещание не должно превращаться в сбор данных. Участники приходят к одной отчетной дате, а обсуждают причины и действия. Если половина встречи уходит на выяснение, какая версия таблицы верная, сначала нужно исправить контур факта.</p>

<h2>Что должно быть на панели руководителя</h2>

<p>Полезная панель начинается с портфеля и позволяет провалиться до причины. На верхнем уровне достаточно видеть прогноз окончания, изменение к базовой дате, ожидаемую итоговую стоимость, незакрытые объемы и критические ограничения. Двадцать зеленых показателей не компенсируют один скрытый риск.</p>

<p>Каждый красный показатель должен вести к объекту управления: работе, договору, заявке, поставке, замечанию или документу. Иначе руководитель получает сигнал, но вынужден просить сотрудников вручную собирать объяснение.</p>

<h2>Как классифицировать причины отклонений</h2>

<p>Свободный комментарий нужен для контекста, но непригоден для накопительного анализа. Одну и ту же проблему сотрудники назовут «нет проекта», «не выдали чертеж», «ожидаем РД» или «нет фронта». В отчете получатся четыре причины вместо одной. Поэтому для первого уровня используют короткий справочник, а подробности оставляют в пояснении.</p>

<ul>
<li>проектные решения и изменения рабочей документации;</li>
<li>неготовый фронт или нарушение последовательности;</li>
<li>материалы и оборудование;</li>
<li>рабочая сила, техника и производительность;</li>
<li>качество, замечания и повторное выполнение;</li>
<li>договорные решения и согласования;</li>
<li>внешние условия, которые команда не может устранить самостоятельно.</li>
</ul>

<p>Причина должна назначаться не по первому впечатлению, а после короткой проверки. Если бригада простаивает без материала, непосредственная причина — поставка. Но корневая причина может быть в поздней заявке из-за несвоевременного выпуска документации. Для недельного решения достаточно устранить ограничение, а для улучшения процесса важно сохранить оба уровня.</p>

<p>Через несколько периодов можно построить диаграмму повторяемости и стоимости причин. Она покажет, где теряется больше времени: в отдельных аварийных случаях или в десятках мелких ожиданий. Такой анализ полезнее рейтинга виновных, потому что направляет изменения на маршрут, норматив срока и качество исходных данных.</p>

<h2>Сценарии вместо одного прогноза</h2>

<p>Для крупного риска полезно рассчитать не одну дату, а три сценария. Базовый предполагает наиболее вероятную производительность и подтвержденные ресурсы. Оптимистичный показывает эффект конкретного ускорения. Консервативный учитывает сохранение ограничения или повторный сбой. У каждого сценария должны быть явные предпосылки, иначе цветные линии создают только иллюзию точности.</p>

<p>Сценарий становится решением, когда к нему привязана цена и действие. Дополнительная смена может вернуть контрольную точку, но увеличить затраты; изменение последовательности сохранит дату без прямых расходов, но перенесет риск на другой фронт. Руководитель выбирает компромисс осознанно и затем сравнивает фактический результат с выбранным вариантом.</p>

<p><a href="/construction-budget-control">МОСТ</a> — система управления строительством для подрядчиков и генподрядчиков. В ней план, фактические данные с объекта, задачи, заявки, договоры и документы можно связать в одном контуре. Руководитель видит не только величину отклонения, но и работу, ограничение и назначенное действие.</p>

<h2>Как внедрить план-факт без большого проекта автоматизации</h2>

<ol>
<li>Выберите один объект и один уровень работ, по которому уже существует план.</li>
<li>Зафиксируйте базовую версию и запретите ее перезапись текущими датами.</li>
<li>Определите измеримый факт и правило его приемки.</li>
<li>Назначьте единую отчетную дату для сроков, объемов и затрат.</li>
<li>Добавьте причину отклонения и обязательное действие для критичных позиций.</li>
<li>Через несколько циклов подключите обязательства и прогноз итоговой стоимости.</li>
</ol>

<p>Качество внедрения оценивается по скорости и надежности решений. Сколько критичных работ не имеют свежего факта? Как быстро назначается действие после отклонения? Насколько прогноз окончания меняется между неделями? Сколько перерасходов обнаруживаются после оплаты, а не до нее?</p>

<h2>Типичные ошибки</h2>

<ul>
<li>Текущий прогноз записывают поверх базового плана.</li>
<li>Процент готовности вводят без правила расчета и подтверждения.</li>
<li>Платеж считают единственным финансовым фактом.</li>
<li>Объемы графика нельзя сопоставить со сметой и актами.</li>
<li>Причины отклонений вводятся свободным текстом и не анализируются.</li>
<li>Красные показатели не имеют владельца следующего действия.</li>
<li>Данные разных объектов собираются на разные отчетные даты.</li>
</ul>

<h2>Частые вопросы</h2>

<h3>Как часто делать план-факт в строительстве?</h3>
