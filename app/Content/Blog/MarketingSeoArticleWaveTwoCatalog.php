<p>Для исполнительной документации применяется отдельное регулирование, включая приказ Минстроя России № 344/пр. Общий журнал связан с исполнительной документацией фактическими событиями, но не заменяет акты освидетельствования, исполнительные схемы, результаты испытаний и специальные журналы.</p>

<p>Если журнал был начат раньше либо объект ведется по специальным отраслевым требованиям, решение о форме нельзя принимать только по дате статьи. Проверьте предписание органа надзора, договор, проект организации строительства и внутренний регламент документооборота.</p>

<h2>Кто ведет общий журнал работ</h2>

<p>Организацию ведения обеспечивает лицо, осуществляющее строительство. На практике ежедневные сведения готовят производители работ, начальники участков и специалисты ПТО, но ответственность нельзя оставлять «на отдел». Для каждого раздела и вида записи нужен назначенный участник.</p>

<ul>
<li>Производитель работ сообщает фактические работы, место, объем, условия и примененные материалы.</li>
<li>ПТО проверяет полноту, ссылки на документацию и согласованность с комплектом исполнительной документации.</li>
<li>Уполномоченный представитель лица, осуществляющего строительство, подписывает записи в пределах своих полномочий.</li>
<li>Представители строительного контроля вносят предусмотренные сведения и замечания.</li>
<li>Орган государственного строительного надзора заполняет относящийся к нему раздел в установленном порядке.</li>
</ul>

<p>Одна фамилия во всех ролях без подтвержденных полномочий создает риск. При изменении специалиста важно своевременно обновить сведения и сохранить основания назначения. Электронная учетная запись также не заменяет полномочие подписанта.</p>

<h2>Когда открывать и начинать записи</h2>

<p>Подготовку начинают до фактического производства: определяют форму, участников, номера, способ ведения и процедуру представления в надзор, если она требуется. Записи о выполнении работ вносятся с начала соответствующих работ, а не после накопления месячного объема.</p>

<p>Для бумажного журнала заранее решают вопросы нумерации, прошивки, регистрации, хранения и доступа. Для электронного — формат, электронные подписи, права, уведомления, выгрузку и долговременное хранение. Скан бумажного листа в общей папке сам по себе не становится электронным журналом.</p>

<h2>Из каких разделов состоит журнал</h2>

<p>Форма по приказу № 1026/пр содержит титульные сведения и разделы, которые заполняются разными участниками. Перед началом полезно разложить ответственность по каждому разделу.</p>

<h3>Раздел 1. Инженерно-технический персонал</h3>
<p>Указываются сотрудники лица, осуществляющего строительство, занятые на объекте. Сведения должны соответствовать назначениям и реальному периоду участия. Изменения состава нельзя оставлять до закрытия объекта.</p>

<h3>Раздел 2. Специальные журналы</h3>
<p>Фиксируется перечень специальных журналов выполнения работ и журналов авторского надзора. Реестр помогает увидеть, какие специализированные процессы документируются отдельно и кто отвечает за соответствующий журнал.</p>

<h3>Раздел 3. Сведения о выполнении работ</h3>
<p>Это основная производственная хронология. Записи должны быть конкретными по месту, содержанию, объему и условиям выполнения. Здесь особенно важна связь с рабочей документацией и фактическими данными площадки.</p>

<h3>Раздел 4. Строительный контроль лица, осуществляющего строительство</h3>
<p>Вносятся сведения о проведенном контроле со стороны подрядчика. Запись должна позволять понять предмет проверки и результат, а не ограничиваться общей формулой «соответствует проекту» без контекста.</p>

<h3>Раздел 5. Строительный контроль застройщика или технического заказчика</h3>
<p>Представитель другой стороны фиксирует проведенный контроль и замечания в пределах своих полномочий. Исполнение замечания должно прослеживаться до результата проверки.</p>

<h3>Раздел 6. Государственный строительный надзор</h3>
<p>Раздел предназначен для сведений органа надзора. Подрядчик не должен заполнять его вместо уполномоченного лица или самостоятельно «закрывать» замечание.</p>

<h2>Как писать сведения о выполненных работах</h2>

<p>Хорошая запись отвечает на несколько вопросов без устного пояснения:</p>

<ul>
<li>что именно выполнено;</li>
<li>где выполнено: объект, этаж, помещение, оси, отметки, захватка;</li>
<li>какой объем и единица измерения;</li>
<li>по какой рабочей документации и версии;</li>
<li>какие существенные условия влияли на производство;</li>
<li>какие материалы, конструкции или оборудование применялись;</li>
<li>какие испытания, контроль или освидетельствование связаны с результатом.</li>
</ul>

<p>Фраза «велись монолитные работы» слишком общая. Она не показывает конструкцию, место, операцию и объем. Более содержательный вариант: «Выполнено бетонирование плиты перекрытия на отметке +6,000 в осях 2–6/А–Г, участок П-2, объем 84 м³, по листам КЖ-24–КЖ-27 версии 3; бетон класса В25, партия указана в журнале бетонных работ». Конкретные реквизиты всегда берутся из фактических документов объекта.</p>

<p>Не стоит превращать запись в копию технологической карты. Журнал фиксирует событие, а подробная технология хранится в соответствующем документе. Ссылка должна быть достаточной, чтобы найти основание и подтверждение.</p>

<h2>Что писать, если работы не выполнялись</h2>

<p>Нельзя заполнять паузу вымышленным производством. Если отсутствие работ связано с существенными условиями — остановкой по замечанию, отсутствием фронта, погодным ограничением или ожиданием решения, — факт фиксируют в соответствии с применимым порядком и внутренним регламентом. Причина должна совпадать с уведомлениями, задачами и другими документами.</p>

<p>Формулировка «работы не велись» без контекста мало помогает. При существенной остановке укажите участок, затронутый процесс, основание, принятые меры и связанный документ. Но не добавляйте в официальный журнал сведения только ради заполнения каждого календарного дня, если применимый порядок этого не требует.</p>

<h2>Как исправлять записи</h2>

<p>Тихо удалять или переписывать исходную запись нельзя. Исправление должно сохранять первоначальное содержание, автора, время и основание изменения в порядке, предусмотренном формой ведения. Для бумаги и электронной формы процедуры различаются, поэтому их нужно закрепить до начала работ.</p>

<p>В электронной системе история изменений должна быть доступна на протяжении срока хранения. Недостаточно хранить только последнее значение поля. Важно видеть, кто внес изменение, когда, что было исправлено и какой подписью оно подтверждено.</p>

<p>Частые исправления задним числом — индикатор плохого процесса. Причиной обычно становится поздний сбор факта, копирование из разрозненных отчетов или отсутствие проверки перед подписанием. Устранение причины полезнее ужесточения наказаний за опечатки.</p>

