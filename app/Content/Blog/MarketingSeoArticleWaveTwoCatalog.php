<h2>Что такое план-фактный анализ в строительстве</h2>

<p>План-факт — это регулярное сравнение базовых показателей проекта с фактическими значениями на выбранную дату. Базой может быть утвержденный график, бюджет, ведомость объемов или договорный план закрытия. Факт должен иметь источник, дату и правило приемки. Разница между ними называется отклонением, но сама по себе она еще не является управленческим выводом.</p>

<p>Если работа должна быть выполнена на 60%, а подтверждено 45%, отклонение составляет 15 процентных пунктов. Чтобы принять решение, нужно знать остаточный объем, текущую производительность, доступный фронт, ресурсы и влияние на следующие работы. Поэтому рядом с планом и фактом нужен прогноз.</p>

<p>Базовый план нельзя незаметно заменять текущим прогнозом. Иначе через несколько обновлений объект снова будет выглядеть идущим «по плану», хотя договорная дата уже перенесена на месяц. Изменять базу можно только отдельным решением с причиной и сохранением предыдущей версии.</p>

<h2>Какие контуры сравнивать</h2>

<h3>Сроки</h3>
<p>Сравниваются базовые и фактические даты начала и окончания, контрольные точки, длительность и актуальный прогноз. Для незавершенной работы важнее прогноз окончания, чем просроченный план: он показывает масштаб последствий и позволяет перестроить следующую цепочку.</p>

<h3>Физические объемы</h3>
<p>Факт измеряется в кубометрах, квадратных метрах, тоннах, штуках, участках или другом проверяемом результате. Процент готовности допустим, если правило его расчета определено заранее. Ответ «почти закончили» нельзя сравнить с бюджетом и использовать для прогноза.</p>

<h3>Стоимость</h3>
<p>Нужно различать бюджет, принятые обязательства, поставленный ресурс, выполненные работы, подтвержденные акты и платежи. Это разные стадии денежного контура. Оплата не доказывает физическую готовность, а выполненный объем не означает, что выручка уже принята заказчиком.</p>

<h3>Документальное закрытие</h3>
<p>Физический факт сравнивается с готовностью исполнительной документации и актированием. Если производство стабильно опережает документы, проект накапливает объем, который сложно предъявить и оплатить. Отдельная статья о <a href="/blog/ispolnitelnaya-dokumentaciya-v-stroitelstve">ведении исполнительной документации</a> разбирает этот контур подробнее.</p>

