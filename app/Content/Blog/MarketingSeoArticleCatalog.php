<p>Порядок ведения исполнительной документации и ее состав задаются нормативными требованиями. В России базовым документом является приказ Минстроя России от 16 мая 2023 года № 344/пр. Общий журнал, в котором ведется учет выполнения работ, регулируется отдельным приказом Минстроя России от 2 декабря 2022 года № 1026/пр. Реквизиты и актуальность документов лучше проверять по официальной публикации перед формированием регламента конкретного объекта.</p>

<h2>Что входит в исполнительную документацию</h2>

<p>Универсального одинакового списка для всех объектов нет. Состав зависит от видов работ, проектных решений, результатов контроля и обязательных требований. Однако рабочий реестр обычно включает несколько групп.</p>

<h3>Акты освидетельствования</h3>

<p>Акты фиксируют результаты работ, которые становятся недоступны для контроля после следующей операции, ответственные конструкции и участки сетей инженерно-технического обеспечения. К акту прикладывают документы, подтверждающие качество, схемы, результаты испытаний и другие материалы, если они требуются для конкретной работы.</p>

<p>Ключевой риск — оформление задним числом. Участники могут помнить дату по-разному, представитель контроля уже не может осмотреть результат, а приложения приходится собирать по косвенным признакам. Поэтому готовность к освидетельствованию должна быть частью производственной задачи.</p>

<h3>Исполнительные схемы и чертежи</h3>

<p>Схемы отражают фактическое положение конструкций, элементов и сетей, в том числе отклонения от проектного положения в допустимых пределах и согласованные изменения. Они должны однозначно относиться к объекту и участку, содержать необходимые измерения и реквизиты исполнителей.</p>

<p>Схема, созданная по памяти после закрытия работ, не выполняет свою функцию. Геодезические и линейные данные нужно передавать в ПТО в установленный срок и сразу связывать с актом и участком.</p>

<h3>Журналы работ</h3>

<p>Общий журнал отражает последовательность выполнения строительства, реконструкции или капитального ремонта и сведения о строительном контроле. Для отдельных процессов применяются специальные журналы, если это следует из требований к соответствующим работам.</p>

<p>Журнал не заменяет оперативный отчет и наоборот. Запись в корпоративной системе помогает управлять задачей, фотографиями и фактом, но обязательные формы и порядок ведения нужно соблюдать отдельно. Рациональная цифровая схема использует один исходный факт для обоих контуров и не заставляет сотрудника несколько раз вводить одинаковые сведения.</p>

<h3>Документы на материалы, изделия и оборудование</h3>

<p>К этой группе относятся паспорта, сертификаты, декларации, документы о качестве, результаты входного контроля и иные подтверждения, предусмотренные для примененной продукции. Документ важно связать не только с поставкой, но и с фактическим местом использования.</p>

<p>Папка из сотен паспортов без привязки к партиям и участкам создает видимость полноты. При проверке сотруднику все равно приходится восстанавливать, какой материал попал в конкретную конструкцию. Связка «поставка — приемка — партия — участок — работа — акт» снимает эту проблему.</p>

<h3>Протоколы, испытания и заключения</h3>

<p>Результаты лабораторного контроля, опробования, измерений, пусконаладки и проверки систем включаются в комплект по соответствующим работам. В графике нужно учитывать срок вызова специалиста, проведение процедуры и получение оформленного результата. Сам факт отбора образца еще не означает готовность документа.</p>

<h3>Рабочая документация с отметками</h3>

<p>Комплект должен отражать фактическое исполнение и согласованные изменения в предусмотренном порядке. Для команды критична версионность: на площадке должна использоваться действующая версия, а ПТО должно понимать, по какому решению выполнен участок.</p>

<h2>Кто отвечает за ведение</h2>

<p>Формальная ответственность определяется законодательством, договором и назначениями участников. В рабочем процессе обязанности обычно распределяются между производителем работ, ПТО, геодезистами, лабораторией, представителями строительного контроля, проектной организации и ответственными со стороны подрядчиков.</p>

<p>ПТО не может создать достоверный факт вместо площадки. Прораб или мастер сообщает о готовности, месте, времени и примененных материалах. Геодезист и лаборатория передают свои результаты. ПТО проверяет комплектность, реквизиты, взаимные ссылки, версии и движение на подписание. Руководитель проекта обеспечивает сроки и снимает организационные ограничения.</p>

<p>Полезно назначать ответственность не «за исполнительную документацию вообще», а за каждый переход: кто создает заявку на освидетельствование, кто формирует схему, кто проверяет приложение, кто передает подписанный экземпляр, кто закрывает запись в реестре. Тогда задержка имеет конкретного владельца.</p>

<h2>Когда оформлять документы</h2>

<p>Точка оформления определяется технологией. Если следующая работа закрывает результат, контроль и фиксация должны произойти до ее начала. В календарном плане это отдельное условие передачи фронта, а не необязательная административная операция.</p>

<p>Для каждого вида работ полезно подготовить матрицу исполнительной документации. В строке указывают работу или конструктив, требуемые формы, приложения, ответственных, подписантов и контрольный срок. Матрицу связывают с графиком и ведомостью объемов. Тогда будущая потребность видна до выполнения, а не после запроса заказчика.</p>

<p>Рабочий цикл может выглядеть так:</p>

<ol>
<li>До начала проверяются действующая рабочая документация, требуемые формы и документы на материалы.</li>
<li>Во время выполнения фиксируются участок, объем, даты, партия материала, измерения и фотографии.</li>
<li>До закрытия результата создается уведомление о готовности и проводится требуемый контроль.</li>
<li>ПТО собирает акт, схему и приложения, проверяет согласованность реквизитов.</li>
<li>Документ проходит подписание или предусмотренный электронный маршрут.</li>
<li>Финальная версия попадает в реестр и архив с понятным статусом.</li>
</ol>

<p>Такой порядок требует дисциплины, но экономит время на сдаче. Главное — не увеличивать объем ручного ввода. Поля, уже созданные в задаче, заявке, поставке или журнале, должны использоваться повторно.</p>

<h2>Как организовать реестр исполнительной документации</h2>

<p>Реестр должен показывать не только название файла. Для управления нужны объект и участок, вид работ, форма документа, номер, период или дата, ответственный, комплект приложений, текущий статус, подписанты, ссылка на связанную работу и место хранения финальной версии.</p>

<p>Статусы лучше описывать как фактические этапы: ожидает исходных данных, готовится, на внутренней проверке, передан на подписание, возвращен с замечаниями, подписан, включен в комплект. Слишком общий статус «в работе» не помогает понять следующее действие.</p>

<p>Отдельно храните причину возврата. Через несколько недель статистика покажет повторяющиеся ошибки: неверные реквизиты, отсутствие паспорта, расхождение дат, неподписанная схема, неправильная версия формы. После этого регламент можно исправить в точке возникновения, а не усиливать финальную проверку.</p>

<h2>Связь с общим журналом работ</h2>

<p>Даты в журнале, актах, схемах, лабораторных документах и производственном факте должны согласовываться. Расхождение часто появляется потому, что каждый документ ведет отдельный сотрудник в своем файле. Единый исходный факт снижает риск, но не отменяет проверку содержания и требований к форме.</p>

<p>В 2026 году Минстрой России дополнительно разъяснял вопросы порядка формирования и ведения общего журнала работ. При настройке процесса важно ориентироваться на действующий приказ № 1026/пр, а не на старые шаблоны, сохраненные в компании много лет назад. Само письмо Минстроя носит разъяснительный характер и не является нормативным правовым актом.</p>

<p>Оперативная система может напомнить о записи, подставить общие реквизиты и связать подтверждения. Юридически значимый документ формируется и подписывается в том порядке, который применим к объекту и участникам. Эти два уровня нельзя смешивать.</p>

<h2>Электронная исполнительная документация</h2>

<p>Электронный формат — это не сканы бумажных папок на общем диске. Нужны структурированный реестр, контроль версий, роли, история действий, согласованный маршрут, долговременное хранение и применимый способ электронной подписи. Формат и информационная система зависят от требований к объекту и взаимодействия участников.</p>

<p>Перед переходом договоритесь о правилах:</p>

<ul>
<li>какая система является источником финальной версии;</li>
<li>кто создает, проверяет, подписывает и аннулирует документ;</li>
<li>как идентифицируются объект, участок, работа и комплект;</li>
<li>какие форматы файлов и схем принимаются;</li>
<li>как применяется электронная подпись;</li>
<li>как участники получают доступ и как фиксируется история;</li>
<li>как выполняются экспорт, передача и архивное хранение;</li>
<li>что происходит при изменении документа после замечания.</li>
</ul>

<p>Если заказчик и подрядчик используют разные контуры, заранее определите обмен. Не стоит обещать «полностью безбумажную сдачу», пока не проверены требования всех подписантов и принимающей стороны. Разумный первый этап — цифровой производственный реестр и подготовка комплектов, даже если часть финальных документов пока подписывается в другом порядке.</p>

<h2>Фотографии: доказательство или свалка файлов</h2>

<p>Фотография полезна, когда понятно, где, когда, кем и к какой работе она сделана. Общая папка с тысячами кадров почти бесполезна. Для скрытых работ заранее определите обязательные ракурсы, масштаб, привязку к осям или помещению и момент съемки.</p>

<p>Фотофиксация не заменяет акт, схему или контроль, если они требуются. Она подтверждает факт и помогает проверке. Хранить ее лучше рядом с работой и документом, а не в переписке. Тогда при замечании можно быстро открыть исходные материалы и увидеть состояние до закрытия конструкции.</p>

<h2>Типичные ошибки при ведении</h2>

<ul>
<li>Документы начинают собирать после завершения этапа.</li>
<li>ПТО не получает от площадки точный участок, дату, объем и партию материала.</li>
<li>Акт, схема и журнал содержат разные даты или наименования.</li>
<li>Используется старая форма без проверки действующих требований.</li>
<li>Приложения хранятся отдельно и не имеют однозначной связи с актом.</li>
<li>Статус «готово» ставят до получения подписанной финальной версии.</li>
<li>Документы на материалы не связаны с фактическим применением.</li>
<li>Файлы называются произвольно, а версии перезаписывают.</li>
<li>Замечания при проверке не классифицируются, поэтому ошибки повторяются.</li>
</ul>

<p>Проблемы усиливаются к концу проекта, но возникают в момент производства. Поэтому показатель готовности ИД нужно видеть рядом с физической готовностью работ. Этап, выполненный на площадке на 95 процентов, может быть готов к сдаче только наполовину, если подтверждающие материалы отстают.</p>

<h2>Как проверить готовность комплекта</h2>

<p>Проверку удобно проводить по матрице, а не по общему списку файлов. Для каждого участка сопоставьте проектный объем, фактическое выполнение, требуемые формы, приложения, результаты контроля и финальный статус. Проверьте взаимные ссылки и одинаковое написание объекта, осей, помещений, конструкций и участников.</p>

<p>Перед передачей убедитесь, что:</p>

<ul>
<li>реестр покрывает все выполненные работы, для которых нужен документ;</li>
<li>фактические объемы сопоставлены с актами и схемами;</li>
<li>приложения читаемы, актуальны и относятся к нужному участку;</li>
<li>реквизиты, даты и номера согласованы между документами;</li>
<li>все обязательные проверки и испытания имеют оформленный результат;</li>
<li>замечания закрыты с сохранением истории;</li>
<li>финальные версии защищены от случайной подмены;</li>
<li>подготовлен предусмотренный формат передачи и архив.</li>
</ul>

<h2>Как цифровой контур помогает ПТО и площадке</h2>

<p>Цифровая система полезна не тем, что хранит еще одну копию файла. Она связывает исполнительную документацию с производством. Прораб фиксирует факт и готовность к контролю. ПТО видит будущую потребность по графику, получает исходные данные, формирует комплект и возвращает конкретное замечание. Руководитель проекта видит участки, где физическое выполнение опережает документальное закрытие.</p>

<p>В МОСТ документы можно организовать вокруг объектов, задач, работ, поставок и ответственных. Это помогает не восстанавливать контекст по названию файла и переписке. При этом компания сама определяет обязательные формы, порядок подписания и внешние системы, применимые к конкретному объекту.</p>

<p>Начинать лучше с одного повторяемого вида работ. Создайте матрицу, назначьте роли, определите обязательный полевой факт и проведите несколько комплектов от готовности до архива. После исправления маршрута масштабируйте его на другие разделы.</p>

<h2>Частые вопросы</h2>

<h3>Какие документы относятся к исполнительной документации?</h3>
<p>Состав зависит от объекта и видов работ. Обычно в него входят акты освидетельствования, исполнительные схемы, журналы, документы на материалы, протоколы и результаты испытаний, а также рабочая документация с отметками о фактическом исполнении.</p>

<h3>Можно ли вести исполнительную документацию только в электронном виде?</h3>
<p>Возможность и порядок зависят от применимых требований, информационного взаимодействия и готовности всех участников. Нужно заранее определить систему, форматы, электронную подпись, маршруты, передачу и архив. Простое хранение сканов не является полноценным электронным ведением.</p>

<h3>Кто должен собирать исходные данные для актов?</h3>
<p>Производственная команда фиксирует фактическое выполнение, место, даты, объемы и примененные материалы. ПТО проверяет и оформляет комплект. Конкретную ответственность закрепляют в матрице и регламенте объекта.</p>

<h3>Когда оформлять акт на скрытые работы?</h3>
<p>Контроль и оформление проводят до того, как результат будет закрыт последующей работой и станет недоступен для осмотра. Точный порядок определяют применимые требования и регламент взаимодействия участников.</p>

