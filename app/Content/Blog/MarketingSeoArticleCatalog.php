<h2>Что входит в график производства работ</h2>

<p>График — это перечень работ, расположенных во времени и связанных технологическими и организационными зависимостями. Для каждой работы обычно нужны наименование, место или участок, объем, единица измерения, длительность, плановые даты, исполнитель и предшественники. Для управления добавляют ресурсы, потребность в материалах, контрольные точки, фактические даты и прогноз.</p>

<p>Не стоит смешивать уровни. Договорный график фиксирует обязательства перед заказчиком. Сводный календарный план помогает руководству управлять объектом. Месячно-недельный план дает команде конкретный фронт. Суточное задание определяет действие бригады. Эти уровни должны быть связаны, но степень детализации у них разная.</p>

<p>Если в договорном графике есть строка «Устройство монолитного каркаса», в оперативном плане ее разбивают по захваткам, этажам или конструктивам. Если сразу сделать договорный план из тысяч операций, его будет трудно согласовывать и невозможно читать. Если оставить только десяток укрупненных строк, прораб не сможет по нему организовать смену.</p>

<h2>Какие исходные данные собрать до расчета сроков</h2>

<p>Длительность нельзя надежно получить только из объема и усредненной нормы. На реальном объекте ее определяют фронт, технология, количество звеньев, сменность, доступ к механизму, поставки, согласования и ограничения площадки. Поэтому до расстановки дат соберите хотя бы следующий набор:</p>

<ul>
<li>договорные даты и промежуточные вехи;</li>
<li>рабочую структуру объекта: корпуса, этажи, участки, захватки;</li>
<li>ведомость объемов по этой структуре;</li>
<li>принятую технологическую последовательность;</li>
<li>доступные бригады, механизмы и режим работы;</li>
<li>сроки выдачи документации и согласования решений;</li>
<li>потребность в материалах с длительным сроком поставки;</li>
<li>ограничения по фронтам, безопасности, логистике и временным сетям.</li>
