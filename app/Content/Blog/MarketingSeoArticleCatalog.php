<h2>Частые вопросы</h2>

<h3>Кто должен вести график производства работ?</h3>
<p>За целостность графика отвечает руководитель проекта или назначенный планировщик, но исходный факт дают руководители участков и исполнители. Если один сотрудник пытается самостоятельно угадывать состояние всех работ, обновление всегда будет запаздывать.</p>

<h3>Как часто обновлять график?</h3>
<p>Критичные события и объемы фиксируют по мере возникновения, часто ежедневно. Полный прогноз и недельный план удобно пересматривать в установленный день раз в неделю. На быстро меняющемся этапе период можно сократить.</p>

<h3>Чем базовый план отличается от текущего?</h3>
<p>Базовый план хранит утвержденные даты, относительно которых измеряют отклонение. Текущий прогноз показывает ожидаемые даты с учетом факта, темпа и ограничений. Перенос прогноза не должен автоматически менять базу.</p>

<h3>Можно ли считать график только по проценту готовности?</h3>
<p>Процент допустим, если заранее определен способ расчета. Для надежного прогноза лучше использовать физические объемы, завершенные участки и фактическую производительность, потому что одинаковый процент может скрывать разную трудоемкость остатка.</p>

