<h2>Как вести план-факт без самообмана</h2>

<p>Факт — это не субъективная оценка готовности. Для объемной работы он выражается в физических единицах, принятых ответственным. Для события — датой наступления. Для документа — статусом и датой согласования. Процент используют только тогда, когда понятно, как он рассчитан.</p>

<p>Например, фраза «отделка готова на 80 процентов» плохо прогнозирует окончание: оставшиеся 20 процентов могут включать самые трудоемкие узлы. Надежнее разбить результат по помещениям, видам работ или измеримым объемам. Если это невозможно, задайте вес этапов заранее и не меняйте его под желаемый отчет.</p>

<p>Обновляйте три значения отдельно:</p>

<ul>
<li>базовый план — с чем сравниваем;</li>
<li>факт — что уже произошло и не может быть перепланировано;</li>
<li>прогноз — когда закончим при текущем темпе и известных ограничениях.</li>
</ul>

<p>Красная зона начинается не в день просрочки. Если для работы через две недели требуется материал, который еще не заказан, риск уже существует. Поэтому цикл обновления должен проверять не только завершение текущих операций, но и готовность будущего фронта.</p>

<h2>Еженедельный цикл обновления графика</h2>

<p>Для большинства объектов рабочий график удобно пересматривать раз в неделю, а критичные факты фиксировать ежедневно. К совещанию руководитель проекта собирает выполненные объемы, фактические старты и окончания, изменения ресурсов, состояние поставок и новые ограничения. Данные поступают от ответственных по участкам, а не восстанавливаются планировщиком по фотографиям в общем чате.</p>

<p>На встрече обсуждают отклонения и ближайший горизонт. Для каждой проблемной цепочки выбирают действие: увеличить ресурс, открыть дополнительный фронт, изменить последовательность, ускорить согласование, заменить материал или официально пересмотреть обязательство. Решение получает владельца и срок.</p>

<p>После совещания обновляется прогноз, но не базовые даты. Участникам выдают недельный план, связанный с общим графиком. На следующей встрече проверяют не только производство, но и исполнение принятых решений. Такой ритм превращает диаграмму из отчета в инструмент управления.</p>

<h2>Что делать при срыве сроков</h2>

<p>Сначала определите, какая цепочка изменила конечный прогноз. Общее отставание «по объекту» не подсказывает действие. Затем разложите причину: неготовый фронт, нехватка ресурса, низкая производительность, задержка документации, поставки, изменение объема, ошибка последовательности.</p>

<p>Ускорение тоже нужно считать. Дополнительная бригада не поможет, если нет второго фронта или ведущего механизма. Сверхурочная работа увеличивает выпуск не пропорционально часам и может добавить переделки. Перестановка последовательности иногда дает больший эффект, чем наращивание людей, но должна пройти технологическую проверку.</p>

<p>Сценарий восстановления должен содержать новые ресурсы, измененные связи, стоимость решения, риски и контрольные точки. Фраза «нагоним в следующем месяце» без изменения производственной модели не является планом.</p>

<h2>Типичные ошибки в графике</h2>

<ul>
<li>Работы не привязаны к участкам, поэтому одинаковые названия невозможно сопоставить с фактом.</li>
<li>Длительности назначены «по опыту», но состав ресурса и выработка не зафиксированы.</li>
<li>Все операции связаны последовательно, хотя возможен поток по захваткам.</li>
<li>Поставки и согласования считаются внешними событиями и не влияют на даты.</li>
<li>Базовый план перезаписывают текущим прогнозом.</li>
<li>Процент готовности сообщает исполнитель без правила расчета и приемки.</li>
<li>График обновляет один планировщик, а руководители участков не отвечают за исходный факт.</li>
<li>Недельные задания создаются отдельно и не меняют прогноз общего плана.</li>
</ul>

<p>Большинство этих ошибок возникает не из-за программы. Они появляются, когда у графика нет владельца и регулярного цикла. Инструмент может подсветить просрочку, но не определит за команду, какой факт считается принятым и кто обязан снять ограничение.</p>

<h2>Когда Excel перестает справляться</h2>

<p>Для первоначальной модели и небольшого объекта таблицы достаточно. Переход к специализированной системе оправдан, когда один график одновременно меняют несколько участников, нужно ограничивать доступ, связывать задачи и поставки, хранить вложения, видеть историю и автоматически собирать портфель проектов.</p>

<p>Ключевой признак — ручная синхронизация. Если руководитель проекта каждую пятницу копирует факты из отчетов прорабов, сверяет заявки снабжения и затем переносит даты в диаграмму, компания платит за подготовку картинки вместо управления отклонениями.</p>

<p>В МОСТ график можно связать с задачами, ответственными, заявками и фактом с объекта. Руководитель проекта видит не только просроченную полосу, но и контекст: что мешает началу и какое действие назначено. Это особенно полезно в недельном цикле, где скорость обновления важнее сложности исходной модели.</p>

<h2>Чек-лист перед утверждением графика</h2>

