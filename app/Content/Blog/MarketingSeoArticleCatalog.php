<h2>Что такое исполнительная документация</h2>

<p>Исполнительная документация подтверждает фактическое выполнение работ и принятые технические решения. Она показывает, что именно построено, где расположены конструкции и сети, какие материалы применены, кто выполнил и проверил работы, какие испытания проведены и соответствует ли результат установленным требованиям.</p>

