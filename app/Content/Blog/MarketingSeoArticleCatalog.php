<p>Часть исходных данных в начале будет неопределенной. Их нельзя прятать внутри оптимистичной длительности. Заведите отдельный реестр ограничений и гипотез. Например: «начало фасада возможно после утверждения узла», «второй кран доступен с 15 октября», «окна поставляются партиями по два этажа». У каждой гипотезы должны быть дата проверки и ответственный.</p>

<h2>Как составить график производства работ</h2>

<h3>Шаг 1. Постройте структуру декомпозиции</h3>

<p>Начните не со строк в диаграмме Ганта, а с понятной модели результата. Верхний уровень может повторять этапы договора: подготовка, конструктив, инженерные системы, отделка, благоустройство, пусконаладка. Ниже работы разбиваются по месту и технологии до уровня, на котором можно назначить одного ответственного и подтвердить факт.</p>

<p>Хорошая рабочая операция имеет проверяемый конец: «смонтированы воздуховоды секции 2 на третьем этаже», а не «заниматься вентиляцией». При этом чрезмерная детализация тоже мешает. Если операция длится несколько часов и не влияет на передачу фронта, ее лучше оставить внутри сменного задания.</p>

<h3>Шаг 2. Определите последовательность и зависимости</h3>

<p>Самая распространенная связь — следующая работа начинается после окончания предыдущей. Но в строительстве часто встречается поточная организация: следующая бригада заходит на первую захватку, пока предыдущая продолжает на второй. Тогда работы можно связать по участкам или задать допустимый лаг.</p>

<p>Проверяйте смысл каждой связи. Не связывайте строки только ради красивой непрерывной диаграммы. Зависимость должна отвечать на вопрос: какое физическое, договорное или организационное условие не позволяет начать раньше? Так легче увидеть, какие ограничения можно снять управленческим решением.</p>

<h3>Шаг 3. Рассчитайте длительность через производительность</h3>

<p>Базовый расчет прост: объем делится на производительность выбранного состава бригады с учетом сменности. Затем результат проверяют по доступному фронту и технологии. Если расчет требует десять звеньев, а одновременно на участке помещается три, формальная длительность не реализуема.</p>

<p>Зафиксируйте допущение рядом с работой: состав бригады, смены, ведущий механизм, плановая выработка. После появления факта вы сможете сравнить не только даты, но и реальный темп. Это полезнее фразы «подрядчик идет медленно».</p>

<h3>Шаг 4. Добавьте ресурсы и поставки</h3>

<p>Календарь без ресурсов может одновременно назначить один кран пяти бригадам. Проверьте загрузку ключевых механизмов, мастеров, лабораторий и специализированных подрядчиков. Не обязательно ресурсно выравнивать каждую мелкую операцию, но дефицитные ресурсы должны быть видны.</p>

<p>Поставки привязывайте к дате потребности с запасом на приемку и возможное отклонение. Для заказных изделий график должен включать не только доставку, но и выдачу исходных данных, согласование, производство и логистику. Срочная закупка редко исправляет пропущенное согласование, которое произошло два месяца назад.</p>

<h3>Шаг 5. Найдите критический путь и резервы</h3>

<p>Критический путь — последовательность работ, задержка которой сдвигает конечную дату при текущих связях и длительностях. Это не постоянный список «самых важных работ». Он меняется после обновления факта, изменения логики или использования резервов.</p>

<p>Руководителю проекта полезно видеть также близкие к критическим цепочки. Работа с небольшим резервом может стать критической после одной несогласованной замены. Управленческое внимание следует распределять по размеру резерва и цене задержки, а не по громкости исполнителя.</p>

<h3>Шаг 6. Зафиксируйте базовый план</h3>

<p>После проверки и утверждения сохраните исходные даты отдельной базовой версией. Не заменяйте их текущим прогнозом. Иначе через два месяца отчет покажет идеальное совпадение: план просто повторит фактическое движение.</p>

<p>Изменение базового плана допустимо, если изменились утвержденные обязательства или объем проекта. Такое решение оформляют отдельно с причиной и датой. Оперативное отставание само по себе не является основанием стереть первоначальный срок.</p>

