<h2>Как документ превращается в структуру сметы</h2>

<p>Сначала система определяет тип страниц и качество исходника. Текстовый PDF можно разобрать напрямую. Для скана потребуется распознавание, причём повёрнутые страницы, печати и слабый контраст увеличивают число ошибок. Затем программа восстанавливает таблицу: отделяет заголовки от строк, связывает переносы и определяет колонки.</p>

<p>На следующем шаге строки приводятся к общей структуре. «м2», «м²» и «кв. м» становятся одной единицей, но исходное значение сохраняется. Составные позиции нельзя механически дробить: монтаж оборудования может включать работу, механизм и комплект расходных материалов. Если уверенности недостаточно, строка должна попасть в список на проверку, а не исчезнуть.</p>

<h2>Что проверять перед публикацией</h2>

<p>Начните с контрольных итогов. Сумма по разделам и документу должна совпасть с исходником либо иметь понятное объяснение расхождения. После этого проверьте строки с низкой уверенностью распознавания, пустые цены, необычные единицы и позиции, где количество равно нулю.</p>

<p>Отдельного внимания требуют десятичные разделители. Значение «1 250,50» нельзя превратить в 125 050. Не менее опасны смещённые колонки: цена попадает в количество, а итог — в цену. Несколько выборочных строк из разных частей документа обычно быстро показывают системную ошибку.</p>

