<?php

declare(strict_types=1);

namespace App\BusinessModules\Features\AIAssistant\Services\RequestUnderstanding;

final class AssistantTemporalIntent
{
    private const CALENDAR = '(?<!\pL)(?:январ[а-яё]*|феврал[а-яё]*|март[а-яё]*|апрел[а-яё]*|ма[йеяю]|июн[а-яё]*|июл[а-яё]*|август[а-яё]*|сентябр[а-яё]*|октябр[а-яё]*|ноябр[а-яё]*|декабр[а-яё]*)(?!\pL)|(?<!\d)\d{4}(?=\s*г(?:од[а-яё]*)?(?!\pL))|(?<!\pL)(?:в|за|на|с|до|по|после)\s+\d{4}(?!\d)(?!\s*(?:руб|₽|RUB|доллар|USD|евро|EUR))|(?<!\d)\d{4}(?=[.\/-](?:0?[1-9]|1[0-2])[.\/-])|(?<![\d.\/-])(?:0?[1-9]|[12]\d|3[01])[.\/-](?:0?[1-9]|1[0-2])(?:[.\/-]\d{2,4})?(?!\d)(?!\s*(?:руб|₽|RUB|доллар|USD|евро|EUR))';

    public static function hasExplicitWindow(string $query): bool
    {
        if (preg_match('/(?:заканчив|оканчива|истека)[а-яё]*[^.!?;]{0,60}сегодня|(?:срок|дат)[а-яё]*\s+окончан[а-яё]*\s+(?:на\s+)?сегодня/iu', $query) !== 1) {
            $query = preg_replace('/(?:по\s+состоянию\s+)?на\s+сегодня(?:шний\s+день)?/iu', '', $query) ?? $query;
        }
        return preg_match('/'.self::CALENDAR.'|сегодня|завтра|вчера|(?<!\pL)(?:день|дня|дней|сутки|суток|недел[а-яё]*|месяц[а-яё]*|год|года|году|лет|квартал[а-яё]*|период[а-яё]*)(?!\pL)/iu', $query) === 1;
    }

    public static function hasNonCurrentScope(string $query): bool
    {
        $query = preg_replace('/(?:по\s+состоянию\s+)?на\s+(?:сегодня(?:шний\s+день)?|сейчас|текущую\s+дату)/iu', '', $query) ?? $query;
        return preg_match('/'.self::CALENDAR.'|вчера|завтра|раньше|ранее|прежн|истори|действовал|(?<!\pL)был[аои]?(?!\pL)|(?:будут|будет)\s+(?:ли\s+)?действовать|(?:настройк[а-яё]*|лимит[а-яё]*|порог[а-яё]*)\s+(?:будет|будут)|(?:прошл|следующ|предыдущ|будущ|позапрошл)[а-яё]*\s+(?:(?:рабоч|календарн)[а-яё]*\s+)?(?:месяц|год|недел|квартал|полугод|день|дня|дней|сутк|час|сезон)|(?<!\pL)(?:понедельн|вторник|среда|среду|среде|среды|четверг|пятниц|суббот|воскресен|выходн)[а-яё]*(?!\pL)|(?:через|спустя)\s+(?:[\pL\d]+\s+){0,3}(?:день|дня|дней|сутки|суток|недел[а-яё]*|месяц[а-яё]*|год|года|лет|час[а-яё]*)(?!\pL)|(?:день|дня|дней|сутки|суток|недел[а-яё]*|месяц[а-яё]*|год|года|лет|час[а-яё]*)\s+назад|до\s+(?:изменен|обновлен)|на\s+дату|по\s+состоянию\s+на/iu', $query) === 1;
    }
}
